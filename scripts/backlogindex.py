"""Render the generated half of a backlog index from its task files.

The index is two documents in one file. Above `BEGIN` a person writes what the backlog is
and how to work it; between `BEGIN` and `END` this module writes what is in it. Nothing in
the generated half is typed by hand, so no count here can drift from the files it counts:
a number that disagrees with the tasks is a rendering bug, not a bookkeeping lapse, and
`backlogcheck.py` fails the gate on it before anybody reads it.

Order is fixed rather than clever. The open buckets come first, in the order a reader
should try them (what is actionable now, then what waits on a seam, then the three kinds of
deliberate wait), because "what remains" is the question this file exists to answer. The
per-group roll call comes second and holds every task, open or closed, because a landed
entry is this backlog's record of what a deferral became and finding it is the other
question people arrive with.
"""

from backlog import NEEDS_TRIGGER, OPEN_STATES, UNRECORDED, Status, Task

BEGIN = "<!-- backlog:begin (generated by `just backlog`; edit the task files, not this block) -->"
END = "<!-- backlog:end -->"

BUCKET_ORDER = (
    *OPEN_STATES.values(),
    "Never attempted",
    "Attempted, inconclusive",
)
CLOSED_ORDER = ("Landed", "Declined", "Satisfied", "Done")


def _describe(status: Status) -> str:
    """Return the short status phrase shown in a roll-call line."""
    if status.state in OPEN_STATES:
        return f"open, {status.state}"
    if status.is_standing:
        return f"{status.state}: {status.detail}"
    if status.on is None:
        return status.state
    return f"{status.state} {status.on.isoformat()}"


def _standing_section(tasks: list[Task]) -> list[str]:
    """Return the standing items, which are neither remaining work nor finished."""
    standing = sorted(
        (task for task in tasks if task.status.is_standing), key=lambda item: item.number
    )
    if not standing:
        return []
    lines = [f"## Standing, never closes ({len(standing)})", ""]
    lines.append(
        "Neither work that remains nor work that finishes: an observation made over time, or an "
        "obligation on every change. They are counted apart so that neither number lies."
    )
    lines.append("")
    lines.extend(
        f"- **{_link(task)}** {task.title} ({task.group}): {task.status.detail}."
        for task in standing
    )
    lines.append("")
    return lines


def _link(task: Task) -> str:
    """Return the markdown link to ``task``, relative to its index."""
    return f"[{task.ident}](tasks/{task.path.name})"


def _open_section(tasks: list[Task]) -> list[str]:
    """Return the "what remains" half: every open task under its bucket heading."""
    lines: list[str] = []
    for bucket in BUCKET_ORDER:
        in_bucket = [task for task in tasks if task.status.is_open and task.status.bucket == bucket]
        if not in_bucket:
            continue
        lines.append(f"### {bucket} ({len(in_bucket)})")
        lines.append("")
        for task in sorted(in_bucket, key=lambda item: item.number):
            entry = f"- **{_link(task)}** {task.title} ({task.group})."
            trigger = task.fields.get("Trigger")
            if trigger and task.status.state in NEEDS_TRIGGER:
                entry += (
                    " No trigger was ever recorded for it."
                    if trigger == UNRECORDED
                    else f" Reopens when: {trigger}"
                )
            lines.append(entry)
        lines.append("")
    return lines


def _group_section(tasks: list[Task], group_word: str) -> list[str]:
    """Return the roll call: every task, open and closed, under its group heading."""
    lines: list[str] = []
    groups = sorted({task.group for task in tasks})
    for group in groups:
        members = sorted(
            (task for task in tasks if task.group == group), key=lambda item: item.number
        )
        opens = [task for task in members if task.status.is_open]
        lines.append(f"### {group}")
        lines.append("")
        lines.append(f"{len(opens)} open of {len(members)}.")
        lines.append("")
        lines.extend(f"- {_link(task)} {task.title}. {_describe(task.status)}." for task in members)
        lines.append("")
    if not groups:
        lines.append(f"No {group_word} holds a task yet.")
        lines.append("")
    return lines


def render(tasks: list[Task], group_word: str) -> str:
    """Return the whole generated block for ``tasks``, markers included."""
    opens = [task for task in tasks if task.status.is_open]
    standing = [task for task in tasks if task.status.is_standing]
    closed = len(tasks) - len(opens) - len(standing)
    counted = f"**{len(opens)} open, "
    if standing:
        counted += f"{len(standing)} standing, "
    lines = [BEGIN, "", f"{counted}{closed} closed, {len(tasks)} in total.**", ""]
    lines.append("## What remains")
    lines.append("")
    blank = [
        task
        for task in tasks
        if task.status.state in NEEDS_TRIGGER and task.fields.get("Trigger") == UNRECORDED
    ]
    if blank:
        # This count exists to be driven to zero, so the sentence has to survive its own
        # last reading: "1 of these wait" is the one number where the plural is wrong, and
        # it is the number a reader sees on the pass that finishes the job.
        opener = "One of these waits" if len(blank) == 1 else f"{len(blank)} of these wait"
        lines.append(
            f"{opener} on something nobody wrote down. That is a gap in the "
            f"record rather than a decision, and reading one of them closes it."
        )
        lines.append("")
    if opens:
        lines.extend(_open_section(tasks))
    else:
        lines.append("Nothing. Every task here is closed.")
        lines.append("")
    lines.extend(_standing_section(tasks))
    lines.append(f"## Every task, by {group_word}")
    lines.append("")
    lines.extend(_group_section(tasks, group_word))
    lines.append(END)
    return "\n".join(lines)


def splice(existing: str, block: str) -> str:
    """Return ``existing`` with its generated block replaced by ``block``."""
    start = existing.find(BEGIN)
    end = existing.find(END)
    if start == -1 or end == -1 or end < start:
        msg = f"the index needs both {BEGIN!r} and {END!r}, in that order"
        raise ValueError(msg)
    return existing[:start] + block + existing[end + len(END) :]
