GLYPH_WIDTH = 5
GLYPH_HEIGHT = 8

_GLYPHS: dict[str, tuple[str, ...]] = {char: tuple(rows.split(" ")) for char, rows in _ROWS.items()}


def glyph(char: str) -> tuple[str, ...]:
    """The eight row-bit strings for ``char``, or a filled box when the table has no entry."""
    return _GLYPHS.get(char, ("11111",) * GLYPH_HEIGHT)


def missing(text: str) -> tuple[str, ...]:
    """Every distinct character of ``text`` this font cannot draw, in first-seen order."""
    seen: list[str] = []
    for char in text:
        if char not in _GLYPHS and char not in seen:
            seen.append(char)
    return tuple(seen)
